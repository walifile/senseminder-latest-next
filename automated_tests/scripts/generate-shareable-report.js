const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const archiver = require('archiver');

// Function to create zip file using archiver
function createZipFile(sourceDir, zipPath) {
    return new Promise((resolve, reject) => {
        const output = fs.createWriteStream(zipPath);
        const archive = archiver('zip', { zlib: { level: 9 } });

        output.on('close', () => {
            console.log(`📦 Archive created: ${archive.pointer()} total bytes`);
            resolve();
        });

        archive.on('error', (err) => {
            reject(err);
        });

        archive.pipe(output);
        archive.directory(sourceDir, false);
        archive.finalize();
    });
}

async function main() {
    console.log('🚀 Generating shareable Allure report...');

    // Ensure allure-results exists
    if (!fs.existsSync('allure-results')) {
        console.log('❌ No allure-results found. Please run tests first.');
        process.exit(1);
    }

    // Generate the report
    console.log('📊 Generating Allure report...');
    try {
        execSync('npx allure generate allure-results --output allure-report', { stdio: 'inherit' });
        console.log('✅ Allure report generated successfully');
    } catch (error) {
        console.error('❌ Failed to generate Allure report:', error.message);
        process.exit(1);
    }

    // Create a shareable package
    const timestamp = new Date().toISOString().split('T')[0];
    const shareableDir = `allure-report-shareable-${timestamp}`;

    console.log(`📦 Creating shareable package: ${shareableDir}`);

    // Copy the report to a new directory
    try {
        execSync(`xcopy "allure-report" "${shareableDir}" /E /I /H`, { stdio: 'inherit' });
        
        // Create a README file
        const readmeContent = `# Allure Test Report

## How to View This Report

1. Open the \`index.html\` file in any web browser
2. The report is completely self-contained and doesn't require internet connection

## Report Details

- Generated on: ${new Date().toLocaleString()}
- Test framework: Cucumber.js + Playwright
- Report format: Allure

## Files Included

- \`index.html\` - Main report file
- \`data/\` - Report data files
- \`static/\` - CSS and JavaScript files

## Notes

This report contains test execution results and may include sensitive information.
Please handle accordingly.

---
Generated by SensePC Test Automation
`;

        fs.writeFileSync(path.join(shareableDir, 'README.md'), readmeContent);
        
        console.log(`✅ Shareable report created in: ${shareableDir}`);
        console.log(`📁 Main report file: ${shareableDir}/index.html`);
        console.log(`📋 Instructions: ${shareableDir}/README.md`);
        
        // Create a zip file
        console.log('📦 Creating zip file...');
        await createZipFile(shareableDir, `${shareableDir}.zip`);
        console.log(`✅ Zip file created: ${shareableDir}.zip`);
        
    } catch (error) {
        console.error('❌ Failed to create shareable package:', error.message);
        process.exit(1);
    }

    console.log('\n🎉 Shareable report ready!');
    console.log(`📤 Share this file: ${shareableDir}.zip`);
    console.log(`🌐 Or share this folder: ${shareableDir}/`);
}

// Run the main function
main().catch(error => {
    console.error('❌ Script failed:', error.message);
    process.exit(1);
});
